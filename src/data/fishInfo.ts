export function findFishInfo(species: string | null | undefined): FishSpeciesInfo | undefined {
  if (!species) return undefined;
  const normalized = species.trim().toLocaleLowerCase('tr-TR');
  return FISH_SPECIES_INFO.find(
    (f) => f.species.toLocaleLowerCase('tr-TR') === normalized
  );
}

export const FISH_SPECIES_NAMES = FISH_SPECIES_INFO.map((f) => f.species);
